struct guiRecord_t {
	int		nameAt;		// the record: name length, name, unique flag, state
	int		stateAt;
	idStr	name;
};

// the GUI records in the stream: what idRestoreGame::ReadUserInterface reads
static void FindGuiRecords( const idStr &data, std::vector<guiRecord_t> &records ) {
	const int length = data.Length();
	for ( int p = 0; p + 4 + 9 + 1 <= length; p++ ) {
		int len;
		memcpy( &len, data.c_str() + p, sizeof( len ) );
		if ( len < 9 || len > 128 || p + 4 + len + 1 > length ) {
			continue;
		}
		const char *name = data.c_str() + p + 4;
		if ( idStr::Icmpn( name, "guis/", 5 ) != 0 || idStr::Icmpn( name + len - 4, ".gui", 4 ) != 0 ) {
			continue;
		}
		bool printable = true;
		for ( int i = 0; i < len && printable; i++ ) {
			printable = name[i] > 32 && name[i] < 127;
		}
		const unsigned char unique = data[p + 4 + len];
		if ( !printable || unique > 1 ) {
			continue;
		}
		guiRecord_t r;
		r.nameAt = p;
		r.stateAt = p + 4 + len + 1;
		r.name = idStr( name, 0, len );
		records.push_back( r );
	}
}

static int failures = 0;

static void TestSave( const char *path ) {
	idStr data;
	if ( !ReadOSFile( path, data ) ) {
		printf( "FAIL %s: can't read\n", path );
		failures++;
		return;
	}
	idFile_Memory file( path, data.c_str(), data.Length() );

	// the session's header
	idStr gameName, mapName;
	int version;
	file.ReadString( gameName );
	file.ReadInt( version );
	file.ReadString( mapName );
	saveGameVersion = version & 0xffff;
	printf( "== %s: \"%s\" v%d (DUDE revision %d) %s\n", path, gameName.c_str(), saveGameVersion, version >> 16, mapName.c_str() );

	std::vector<guiRecord_t> records;
	FindGuiRecords( data, records );

	std::vector<idUserInterfaceLocal *> restored;
	int consumed = 0;
	for ( size_t i = 0; i < records.size(); i++ ) {
		const guiRecord_t &r = records[i];
		if ( r.nameAt < consumed ) {
			continue;		// inside the GUI state just read
		}
		idUserInterfaceLocal *gui = new idUserInterfaceLocal();
		gui->InitFromFile( r.name, true, false );

		printed.Clear();
		file.Seek( r.stateAt, FS_SEEK_SET );
		bool ok = false;
		idStr error;
		try {
			ok = gui->ReadFromSaveGame( &file );
		} catch ( restoreError_t &e ) {
			error = e.message;
		}
		const int end = file.Tell();

		// how it went
		const char *how = "as saved";
		if ( !error.IsEmpty() || !ok ) {
			how = "FAILED";
		} else if ( printed.Find( "no longer installed" ) >= 0 ) {
			how = "found by its successor";
		} else if ( printed.Find( "saved with the copy in" ) >= 0 ) {
			how = "another copy";
		} else if ( printed.Find( "-bit engine" ) >= 0 ) {
			how = "other pointer size";
		} else if ( printed.Find( "changed since" ) >= 0 ) {
			how = "changed since (values kept)";
		}
		printf( "  %-40s @%-9d %-28s %d bytes\n", r.name.c_str(), r.nameAt, how, end - r.stateAt );
		if ( !printed.IsEmpty() ) {
			printf( "      %s", printed.c_str() );
		}
		if ( !error.IsEmpty() ) {
			printf( "      error: %s\n", error.c_str() );
		}
		if ( !error.IsEmpty() || !ok ) {
			failures++;
			delete gui;
			break;			// the rest of the stream is out of reach
		}

		// Doom 3: the player's HUD state ends where its PDA's record starts (idPlayer::Save); elsewhere what
		// follows is game data, which only the game reads (a GUI's own state names its file too, so
		// a "record" inside the state just read is no sign of an overrun)
		if ( r.name.Icmp( "guis/hud.gui" ) == 0 && doom3Title.title == GAME_TITLE_DOOM3 ) {
			bool atPda = false;
			for ( size_t j = i + 1; j < records.size() && !atPda; j++ ) {
				atPda = records[j].nameAt == end && records[j].name.Icmp( "guis/pda.gui" ) == 0;
			}
			if ( !atPda ) {
				printf( "  FAIL %s does not end at its PDA's record\n", r.name.c_str() );
				failures++;
			}
		}
		consumed = end;
		restored.push_back( gui );
	}

	// each again in the current format, and back
	for ( size_t i = 0; i < restored.size(); i++ ) {
		idFile_Memory out( "resave" );
		restored[i]->WriteToSaveGame( &out );
		idFile_Memory in( "resave", out.GetDataPtr(), out.Length() );
		idUserInterfaceLocal *gui = new idUserInterfaceLocal();
		gui->InitFromFile( restored[i]->GetSourceFile(), true, false );
		printed.Clear();
		saveGameVersion = SAVEGAME_VERSION;
		bool ok = false;
		try {
			ok = gui->ReadFromSaveGame( &in );
		} catch ( restoreError_t &e ) {
			printed += e.message;
		}
		if ( !ok || in.Tell() != out.Length() || !printed.IsEmpty() ) {
			printf( "  FAIL resave of %s: %s (read %d of %d) %s\n", restored[i]->GetSourceFile(), ok ? "ok" : "failed", in.Tell(), out.Length(), printed.c_str() );
			failures++;
		}
		delete gui;
	}
	for ( size_t i = 0; i < restored.size(); i++ ) {
		delete restored[i];
	}
}


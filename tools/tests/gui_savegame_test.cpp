/*
	Offline test of the savegame GUI state restore: idUserInterfaceLocal::ReadFromSaveGame and the
	readers it drives (neo/ui), run on real savegames.

	Links the engine's own GUI objects from build/ (ui/*.o, framework/File.cpp.o) with the real
	idlib; the engine interfaces they call are stand-ins - a file system over folders given in
	priority order (unpacked paks: the first holding a file wins, as the search path picks it),
	materials that are blank, no fonts, no render worlds. The interface methods nothing here calls
	come from gui_savegame_stubs_*.h, generated by test_gui_savegame.sh from the compiler's list of
	pure virtuals.

	For each savegame, reads the header (game name, version, map), then walks the stream for GUI
	records the way idRestoreGame::ReadUserInterface reads them (a length-prefixed "guis/....gui", a
	unique flag) and restores each into a fresh GUI from the file as installed. Reports per GUI how it
	went (as saved / another copy / found by its successor / failed) and checks that the player's HUD
	ends exactly where its PDA's record starts (the one place the next record is known).
	Then saves every restored GUI again in the current format and reads it back.

	Usage: gui_savegame_test --tables FILE [--quake4] --layer DIR ... [--saved DIR ...] FILE.save ...
	--tables: the names of the paks' table decls, one per line. --quake4: the savegames are Quake 4's
	(GameTitle). --layer: the installed GUI files, highest priority first. --saved: the paks kept in
	a savegames folder (read for old savegames only). Exit status 1 when a restore fails.

	Built and run by tools/test_gui_savegame.sh. No game, no window, no GPU.
*/


static bool ReadOSFile( const std::string &path, idStr &text ) {
	FILE *f = fopen( path.c_str(), "rb" );
	if ( !f ) {
		return false;
	}
	fseek( f, 0, SEEK_END );
	const long len = ftell( f );
	fseek( f, 0, SEEK_SET );
	text.Fill( ' ', (int)len );
	const bool ok = len == 0 || fread( &text[0], 1, len, f ) == (size_t)len;
	fclose( f );
	return ok;
}

// a folder's files by lower-case relative path: pak lookups ignore case (FilenameCompare)
static std::map<std::string, std::map<std::string, std::string>> layerIndex;

static std::string Lower( std::string s ) {
	for ( size_t i = 0; i < s.size(); i++ ) {
		s[i] = (char)tolower( (unsigned char)s[i] );
	}
	return s;
}

static bool ReadLayerFile( const std::string &dir, const char *relativePath, idStr &text ) {
	std::map<std::string, std::string> &index = layerIndex[dir];
	if ( index.empty() ) {
		std::error_code ec;
		for ( std::filesystem::recursive_directory_iterator it( dir, std::filesystem::directory_options::follow_directory_symlink, ec ), end; it != end; it.increment( ec ) ) {
			if ( it->is_regular_file( ec ) ) {
				index[Lower( std::filesystem::relative( it->path(), dir, ec ).generic_string() )] = it->path().string();
			}
		}
		index[""] = "";		// scanned
	}
	std::map<std::string, std::string>::iterator f = index.find( Lower( relativePath ) );
	return f != index.end() && !f->second.empty() && ReadOSFile( f->second, text );
}

static bool FindInLayers( const std::vector<std::string> &dirs, const char *relativePath, idStr &text ) {
	for ( size_t i = 0; i < dirs.size(); i++ ) {
		if ( ReadLayerFile( dirs[i], relativePath, text ) ) {
			return true;
		}
	}
	return false;
}

// idFileSystemLocal::InlineContainerIncludes, for one folder standing in for a pak
static void InlineIncludes( const std::string &dir, idStr &text, int depth ) {
	if ( depth > 4 || text.Find( "#include" ) < 0 ) {
		return;
	}
	idStr result;
	int lineStart = 0;
	while ( lineStart < text.Length() ) {
		int lineEnd = text.Find( '\n', lineStart );
		if ( lineEnd < 0 ) {
			lineEnd = text.Length();
		}
		const idStr line = text.Mid( lineStart, lineEnd - lineStart );
		idStr included;
		int i = 0;
		while ( i < line.Length() && ( line[i] == ' ' || line[i] == '\t' ) ) {
			i++;
		}
		bool replaced = false;
		if ( idStr::Cmpn( line.c_str() + i, "#include", 8 ) == 0 ) {
			const int open = line.Find( '"', i + 8 );
			const int close = ( open >= 0 ) ? line.Find( '"', open + 1 ) : -1;
			if ( close > open + 1 && ReadLayerFile( dir, line.Mid( open + 1, close - open - 1 ), included ) ) {
				InlineIncludes( dir, included, depth + 1 );
				result += included;
				result += "\n";
				replaced = true;
			}
		}
		if ( !replaced ) {
			result += line;
			if ( lineEnd < text.Length() ) {
				result += "\n";
			}
		}
		lineStart = lineEnd + 1;
	}
	text = result;
}

// the engine's FS_ReadFileVersions over the folders
int FS_ReadFileVersions( const char *relativePath, idStrList &texts, idStrList &origins ) {
	texts.Clear();
	origins.Clear();
	for ( int pass = 0; pass < 2; pass++ ) {
		const std::vector<std::string> &dirs = pass ? savedLayers : layers;
		for ( size_t i = 0; i < dirs.size(); i++ ) {
			idStr text;
			if ( !ReadLayerFile( dirs[i], relativePath, text ) ) {
				continue;
			}
			InlineIncludes( dirs[i], text, 0 );
			if ( texts.FindIndex( text ) < 0 ) {
				texts.Append( text );
				origins.Append( dirs[i].c_str() );
			}
		}
	}
	return texts.Num();
}


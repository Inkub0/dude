// a blank material: the GUI code sets its sort, asks its size and name, nothing else here
static struct {
	alignas( 64 ) unsigned char	decl[sizeof( idMaterial )];
	idDeclBaseStub				base;
} blankMaterial;
struct tableStandIn_t {
	alignas( 64 ) unsigned char	decl[sizeof( idDeclTable )];	// blank: an empty table looks up 1
	idDeclBaseStub				base;
};
static std::map<std::string, tableStandIn_t *> tables;
static std::vector<tableStandIn_t *> tablesByIndex;

static void LoadTableNames( const char *path ) {
	FILE *f = fopen( path, "r" );
	char line[256];
	while ( f && fgets( line, sizeof( line ), f ) ) {
		idStr name = line;
		name.StripTrailingWhitespace();
		name.ToLower();
		if ( name.IsEmpty() || tables.count( name.c_str() ) ) {
			continue;
		}
		tableStandIn_t *t = new tableStandIn_t;
		memset( t->decl, 0, sizeof( t->decl ) );
		t->base.index = (int)tables.size();
		reinterpret_cast<idDecl *>( t->decl )->base = &t->base;
		tables[name.c_str()] = t;
		tablesByIndex.push_back( t );
	}
	if ( f ) {
		fclose( f );
	}
}

